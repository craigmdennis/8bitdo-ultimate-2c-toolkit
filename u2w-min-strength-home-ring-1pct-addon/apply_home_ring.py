#!/usr/bin/env python3
"""Add the pairing-safe 1% Home/link-ring patch to the u2w-min-strength Bank A image.

This is an ADD-ON to craigmdennis/8bitdo-ultimate-2c-toolkit branch
u2w-min-strength at commit 69357753e2f51f86f8f6c597863329990040e3f8.

Input must be the 0x24000-byte Bank A image produced by:
    python3 -m u2w_xbox.patch BACKUP.bin BASE.bin

The five hook blobs and ring.bin must be assembled at the addresses documented
in build.sh. This script refuses any unexpected base image or occupied cave.
It writes a new Bank A image; it never writes to a controller.
"""
from __future__ import annotations
import argparse
import hashlib
import math
import struct
import zlib
from pathlib import Path

BANK_A = 0x5000
BANK_END = 0x29000
BANK_SIZE = BANK_END - BANK_A
HSIZE_AT = 0x18
VERSION = 110
RING_ADDR = 0x1C990
RING_EXPECTED_SIZE = 172
RUMBLE_ADDR = 0x1C940
RUMBLE_ROUTINE = bytes.fromhex(
    "204ba24a900200c210ec614be24a910200c211ec224cebaa09c064a800c964a064a900c964a1080b181c591c"
    "7007a4a3580380f9ffa800c9ffa0590389f9ffa900c9ffa17007c04680c70100"
)
RUMBLE_TABLE_ADDR = 0x1C780
MIN_STRENGTH = 28
RUMBLE_TABLE = bytes(
    0 if x == 0 else MIN_STRENGTH + int((255 - MIN_STRENGTH) * math.sqrt(x / 100.0) + 0.5)
    for x in range(101)
)

# Base-branch sentinels. These make sure the input really is the expected
# u2w-min-strength image, not the older PR #15 layout or a stock image.
PNP_ADDR = 0x1B54C
PNP_EXPECTED = bytes.fromhex("02 5e 04 05 0b 01 00")  # 045e:0b05, Xbox Elite Series 2
MAP_LEN_ADDR = 0x1B92C
MAP_LEN_EXPECTED = struct.pack("<I", 98)
CAVE_ADDR = 0x1C880
CAVE = bytes.fromhex(
    "8a6025ec6c06684820406040a848a040e040e848204160412849a041e041a84982f981f0110321426242684982f981f01103"
    "a142e242284808a801c400a0008001b02043e849dba108006043284a7ca10800a04300a00fa1601401b126a9fbc10ea168"
    "1c0aec08b2a01401b11aa9f8c1684ae94942f801a31a0080f004a31800020348f802a31800020388f808a318000203224440"
    "a01da122ec26a3fb97d89f0a60f1979f9d"
)
RUMBLE_HOOK_ADDR = 0xD53E
RUMBLE_HOOK_EXPECTED = bytes.fromhex("0f 90 ff 99")
OUT_REF_ADDR = 0x1C6F0
OUT_REF_EXPECTED = bytes.fromhex("03 02")

# The source bytes at these five firmware hooks are the verified stock 1.10
# sequences. The .bin replacements are generated by build.sh after relocating
# the ring helper to 0x1c990.
HOOKS = {
    "blink_off": (0xF54A, bytes.fromhex("0f 0b 1a 48 20 a1 8a 03 1a 40 d7 87"), 12),
    "blink_on":  (0xF566, bytes.fromhex("08 0b 19 48 20 a2 0a 03 12 f6 12 fe 1a 40 c7 87"), 16),
    "solid_off": (0xF5CA, bytes.fromhex("1b f4 19 fc"), 4),
    "solid_on":  (0xF5EA, bytes.fromhex("1b f4 1a fc"), 4),
    "init":      (0xF71C, bytes.fromhex("10 a2 0a 03 12 f6 12 fe 1a 40"), 10),
}


def checks(bank: bytes) -> tuple[int, int, int]:
    h = struct.unpack_from("<I", bank, HSIZE_AT)[0]
    if h < 0x100 or h > len(bank) - 8:
        raise ValueError(f"Unreasonable Bank A header length: {h:#x}")
    crc = (~zlib.crc32(bank[:h - 4])) & 0xFFFFFFFF
    total = sum(bank[:h - 4]) & 0xFFFFFFFF
    return h, crc, total


def check_crc(bank: bytes, label: str) -> tuple[int, int, int]:
    h, crc, total = checks(bank)
    got = struct.unpack_from("<II", bank, h - 4)
    if got != (crc, total):
        raise ValueError(f"{label}: CRC/startup sum mismatch: stored={got!r}, computed={(crc, total)!r}")
    return h, crc, total


def put(bank: bytearray, addr: int, old: bytes, new: bytes, label: str) -> None:
    off = addr - BANK_A
    if off < 0 or off + len(old) > len(bank):
        raise ValueError(f"{label}: address outside Bank A: {addr:#x}")
    actual = bytes(bank[off:off + len(old)])
    if actual != old:
        raise ValueError(f"{label}: unexpected bytes at {addr:#x}: {actual.hex(' ')}; expected {old.hex(' ')}")
    if len(old) != len(new):
        raise ValueError(f"{label}: replacement length {len(new)} != original length {len(old)}")
    bank[off:off + len(new)] = new


def verify_base(bank: bytes) -> int:
    if len(bank) != BANK_SIZE:
        raise ValueError(f"Expected a Bank A image of {BANK_SIZE:#x} bytes, got {len(bank):#x}")
    if bank[8:12] != b"KNLT" or struct.unpack_from("<H", bank, 2)[0] != VERSION:
        raise ValueError("Input is not firmware 1.10 Bank A")
    h, _, _ = check_crc(bank, "Input Bank A")
    # Current branch's Xbox identity / 38-byte descriptor / cave / rumble / output report.
    if bank[PNP_ADDR - BANK_A:PNP_ADDR - BANK_A + 7] != PNP_EXPECTED:
        raise ValueError("Input is not the expected u2w-min-strength Xbox Elite 045e:0b05 image")
    if bank[MAP_LEN_ADDR - BANK_A:MAP_LEN_ADDR - BANK_A + 4] != MAP_LEN_EXPECTED:
        raise ValueError("Input HID report map length is not the expected 98 bytes")
    if bank[CAVE_ADDR - BANK_A:CAVE_ADDR - BANK_A + len(CAVE)] != CAVE:
        raise ValueError("Input Xbox HID cave does not match u2w-min-strength")
    if bank[RUMBLE_ADDR - BANK_A:RUMBLE_ADDR - BANK_A + len(RUMBLE_ROUTINE)] != RUMBLE_ROUTINE:
        raise ValueError("Input rumble routine does not match u2w-min-strength")
    if bank[RUMBLE_TABLE_ADDR - BANK_A:RUMBLE_TABLE_ADDR - BANK_A + len(RUMBLE_TABLE)] != RUMBLE_TABLE:
        raise ValueError("Input minimum-strength rumble table does not match u2w-min-strength")
    if bank[RUMBLE_HOOK_ADDR - BANK_A:RUMBLE_HOOK_ADDR - BANK_A + 4] != RUMBLE_HOOK_EXPECTED:
        raise ValueError("Input rumble callback does not match u2w-min-strength")
    if bank[OUT_REF_ADDR - BANK_A:OUT_REF_ADDR - BANK_A + 2] != OUT_REF_EXPECTED:
        raise ValueError("Input output report reference does not match u2w-min-strength")
    # The relocated ring helper must be after the rumble routine and finish
    # before the two Bank A integrity words at h-8 and h-4.
    ring_end = RING_ADDR + RING_EXPECTED_SIZE
    if RING_ADDR < RUMBLE_ADDR + len(RUMBLE_ROUTINE):
        raise ValueError("Ring helper overlaps the branch's rumble routine")
    if ring_end > BANK_A + h - 8:
        raise ValueError(f"Ring helper would overlap Bank A integrity words: end={ring_end:#x}, limit={BANK_A+h-8:#x}")
    ring_off = RING_ADDR - BANK_A
    if bank[ring_off:ring_off + RING_EXPECTED_SIZE] != bytes(RING_EXPECTED_SIZE):
        raise ValueError("Relocated ring-helper region at 0x1c990 is not zero-filled; refusing to overwrite")
    # The five code hooks must still be stock. The base branch must not have
    # modified them already.
    for name, (addr, old, _) in HOOKS.items():
        off = addr - BANK_A
        if bank[off:off + len(old)] != old:
            raise ValueError(f"{name} hook at {addr:#x} is not stock; refusing to chain another patch")
    # Existing return/pop after the PWM init hook must remain intact.
    if bank[0xF726 - BANK_A:0xF728 - BANK_A] != bytes.fromhex("00 6d"):
        raise ValueError("Expected original tpop {pc} at 0xf726 was not found")
    return h


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("base_bank_a", type=Path, help="Bank A from u2w_xbox.patch (0x24000 bytes)")
    ap.add_argument("output_bank_a", type=Path, help="new combined Bank A output")
    ap.add_argument("--asm-dir", type=Path, default=Path("/tmp/u2w-ring-asm"), help="directory containing ring.bin and hook .bin files")
    args = ap.parse_args()

    original = args.base_bank_a.read_bytes()
    h = verify_base(original)
    asm = args.asm_dir
    ring = (asm / "ring.bin").read_bytes()
    if len(ring) != RING_EXPECTED_SIZE:
        raise ValueError(f"ring.bin must be {RING_EXPECTED_SIZE} bytes, got {len(ring)}")
    if struct.pack("<I", 0x27100064) not in ring:
        raise ValueError("ring.bin lacks PWM5 1% compare word 0x27100064")
    if struct.pack("<I", 0x27100000) not in ring:
        raise ValueError("ring.bin lacks PWM5 off compare word 0x27100000")
    if struct.pack("<I", 0x8007A8) not in ring:
        raise ValueError("ring.bin does not target PWM5 compare register 0x8007a8")

    out = bytearray(original)
    ring_off = RING_ADDR - BANK_A
    out[ring_off:ring_off + len(ring)] = ring
    for name, (addr, old, n) in HOOKS.items():
        new = (asm / f"{name}.bin").read_bytes()
        if len(new) != n:
            raise ValueError(f"{name}.bin must be {n} bytes, got {len(new)}")
        put(out, addr, old, new, name)

    h, crc, total = checks(out)
    struct.pack_into("<II", out, h - 4, crc, total)
    check_crc(bytes(out), "Combined Bank A")

    # Binary diff must be limited to the ring helper, five hooks and checksums.
    allowed = [(RING_ADDR, len(ring))]
    allowed.extend((addr, len(old)) for addr, old, _ in HOOKS.values())
    allowed.append((BANK_A + h - 4, 8))
    for i, (a, b) in enumerate(zip(original, out)):
        absolute = BANK_A + i
        if a != b and not any(start <= absolute < start + n for start, n in allowed):
            raise AssertionError(f"Unexpected changed byte at {absolute:#x}")

    args.output_bank_a.write_bytes(out)
    print(f"Base Bank A SHA-256: {hashlib.sha256(original).hexdigest()}")
    print(f"Combined Bank A: {len(out)} bytes; SHA-256 {hashlib.sha256(out).hexdigest()}")
    print(f"CRC: {crc:#010x}; startup sum: {total:#010x}; hsize: {h:#x}")
    print(f"Ring helper: {RING_ADDR:#x}-{RING_ADDR+len(ring)-1:#x} ({len(ring)} bytes), PWM5 duty 100/10000 = 1%")
    print("Only Home Ring helper/hooks and Bank A CRC/startup sum were added to the existing u2w-min-strength image.")
    print("Xbox ID, HID map, 38-byte motion report, rumble routine/table and output-report handling were preserved byte-for-byte.")


if __name__ == "__main__":
    main()
